"""Экранирование пользовательского текста для FTS5."""

import re

# Символы, которые FTS5 интерпретирует как операторы
_FTS5_SPECIAL = re.compile(r'["*^(){}:!~\-]')


def fts5_escape(text: str) -> str:
    """Экранирует спецсимволы FTS5, заменяя их на пробелы.

    FTS5 разбирает свой синтаксис запросов: кавычки, звёздочки,
    скобки, двоеточия и т.д. Если передать пользовательский текст
    как есть, он может быть интерпретирован неверно.
    """
    if not text:
        return ""
    return _FTS5_SPECIAL.sub(" ", text).strip()
